G.t = function (key, vars) {
  const L = G.STR[G.settings.lang] || G.STR.en;
  let s = L[key];
  if (s === undefined) s = G.STR.en[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
};

G.applyI18n = function (root) {
  (root || document).querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = G.t(el.getAttribute('data-i18n'));
  });
  document.documentElement.lang = G.settings.lang === 'zh' ? 'zh-CN' : 'en';
};

